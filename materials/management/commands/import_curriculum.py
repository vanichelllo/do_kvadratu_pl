class Command(BaseCommand):
    help = 'Завантажує структуру тем (Класифікатор) у базу даних та лінкує конспекти НМТ'

    def handle(self, *args, **kwargs):
        self.stdout.write("Починаємо імпорт класифікатора...")

        with transaction.atomic():
            # 1. Створюємо дерево тем
            for course_data in ALL_CURRICULUMS:
                subject, _ = CurriculumSubject.objects.get_or_create(
                    name=course_data['course_name'],
                    defaults={'order': course_data['course_order']}
                )

                for grade_data in course_data['grades']:
                    grade, _ = CurriculumGrade.objects.get_or_create(
                        subject=subject,
                        name=grade_data['grade_name'],
                        defaults={
                            'number': grade_data['grade_number'],
                            'order': grade_data['grade_order']
                        }
                    )

                    for chapter_data in grade_data['chapters']:
                        chapter, _ = CurriculumChapter.objects.get_or_create(
                            grade=grade,
                            name=chapter_data['chapter_name'],
                            defaults={'order': chapter_data['chapter_order']}
                        )

                        for topic_data in chapter_data['topics']:
                            CurriculumTopic.objects.get_or_create(
                                chapter=chapter,
                                name=topic_data['topic_name'],
                                defaults={'order': topic_data['topic_order']}
                            )

            special = ensure_special_topics(CurriculumGrade, CurriculumChapter, CurriculumTopic, StudyMaterial)
            self.stdout.write(self.style.SUCCESS(f"✅ Дерево тем успішно завантажено! Нових тем узагальнення й діагностики: {special}"))

            # 2. Магія: Лінкуємо існуючі конспекти НМТ до нового класифікатора
            self.stdout.write("Лінкуємо поточні конспекти НМТ...")

            # Беремо всі теми з курсу "Підготовка до НМТ / ЗНО"
            nmt_topics = CurriculumTopic.objects.filter(chapter__grade__subject__name="Підготовка до НМТ / ЗНО")

            linked_count = 0
            for material in StudyMaterial.objects.filter(curriculum_topic__isnull=True):
                # Шукаємо номер у назві конспекту (наприклад, "34. Теорема косинусів")
                match = re.match(r'^(\d+)', material.title)
                if match:
                    material_num = int(match.group(1))

                    # Шукаємо тему в новому класифікаторі, яка починається з цього ж номера
                    # (наприклад, "34. Теореми косинусів та теорема синусів")
                    for nmt_topic in nmt_topics:
                        topic_match = re.match(r'^(\d+)', nmt_topic.name)
                        if topic_match and int(topic_match.group(1)) == material_num:
                            material.curriculum_topic = nmt_topic
                            material.save(update_fields=['curriculum_topic'])
                            linked_count += 1
                            break

            self.stdout.write(self.style.SUCCESS(f"✅ Знайдено та злінковано {linked_count} конспектів НМТ!"))