# Налаштування gunicorn. Gunicorn сам читає цей файл з кореня проєкту, тому команду
# запуску на Render змінювати не потрібно (параметри з командного рядка мають пріоритет).
import os

# Кількість процесів: на Render її можна задати змінною WEB_CONCURRENCY (за замовчуванням 1)
workers = int(os.getenv('WEB_CONCURRENCY', '1'))

# Кілька потоків у процесі: один повільний запит (Monobank, Gmail, склеювання PDF у боті)
# більше не змушує чекати всіх інших відвідувачів
worker_class = 'gthread'
threads = int(os.getenv('GUNICORN_THREADS', '4'))

# Склеювання «Вся база для НМТ» у боті може тривати до хвилини (стандартний ліміт — 30 с)
timeout = 120
graceful_timeout = 30
